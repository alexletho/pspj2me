#!/usr/bin/env python3
"""Rasterize DejaVu Sans into 8-bit alpha bitmap fonts as C tables (src/gfx/fontdata.c)."""
import sys
from PIL import Image, ImageDraw, ImageFont

REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = [("small", 10), ("medium", 12), ("large", 15)]

codes = list(range(0x20, 0x7f)) + list(range(0xa0, 0x100)) + list(range(0x400, 0x460)) + \
    [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0x2116, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193]
codes = sorted(set(codes))

out = ['/* Generated by tools/genfont.py from DejaVu Sans (Bitstream Vera license, see THIRD_PARTY.md). Do not edit. */',
       '#include "gfx.h"', '']
names = []
for name, px in SIZES:
    for bold, path in ((0, REG), (1, BOLD)):
        font = ImageFont.truetype(path, px)
        asc, desc = font.getmetrics()
        height = asc + desc
        widths, offsets, data = [], [], bytearray()
        for c in codes:
            ch = chr(c)
            adv = int(round(font.getlength(ch)))
            if c == 0x20 or c == 0xa0:
                adv = max(adv, 2)
            adv = max(1, min(adv, 255))
            img = Image.new("L", (adv, height), 0)
            d = ImageDraw.Draw(img)
            d.text((0, asc), ch, font=font, fill=255, anchor="ls")
            offsets.append(len(data))
            widths.append(adv)
            data += img.tobytes()
        sym = f"{name}{'_bold' if bold else ''}"
        names.append(sym)
        out.append(f"static const uint8_t {sym}_bm[{len(data)}] = {{")
        hexs = [str(b) for b in data]
        for i in range(0, len(hexs), 40):
            out.append("  " + ",".join(hexs[i:i+40]) + ",")
        out.append("};")
        out.append(f"static const uint8_t {sym}_w[{len(widths)}] = {{" + ",".join(map(str, widths)) + "};")
        out.append(f"static const uint32_t {sym}_off[{len(offsets)}] = {{" + ",".join(map(str, offsets)) + "};")
        out.append(f"static const BitmapFont font_{sym} = {{ {height}, {asc}, {len(codes)}, font_codes, {sym}_w, {sym}_off, {sym}_bm }};")
        out.append("")
        print(f"{sym}: px={px} height={height} ascent={asc} bytes={len(data)}", file=sys.stderr)
out.insert(3, f"static const uint16_t font_codes[{len(codes)}] = {{" + ",".join(map(str, codes)) + "};")
out.append("const BitmapFont *gfx_font(int sizeIdx, int bold) {")
out.append("    static const BitmapFont *fonts[6] = { " + ", ".join("&font_" + n for n in names) + " };")
out.append("    if (sizeIdx < 0 || sizeIdx > 2) sizeIdx = 1;")
out.append("    return fonts[sizeIdx * 2 + (bold ? 1 : 0)];")
out.append("}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
